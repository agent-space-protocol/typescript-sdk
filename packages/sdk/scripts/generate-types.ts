// Generates src/types/generated.ts from schema/schema.json, the copy of the specification's
// schema.json. Options:
//   --sync <spec-repo>  copy schema/draft/schema.json from a checkout of the specification first
//   --check             exit 1 when the generated types, or the schema copy (with --sync), differ
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const check = args.includes("--check");
const syncAt = args.indexOf("--sync");
const schemaPath = join(pkg, "schema", "schema.json");
let ok = true;

function emit(path: string, content: string) {
  const old = existsSync(path) ? readFileSync(path, "utf8") : undefined;
  if (old === content) return;
  if (check) {
    console.error(`out of date: ${path.slice(pkg.length + 1)}`);
    ok = false;
    return;
  }
  writeFileSync(path, content);
  console.log(`wrote ${path.slice(pkg.length + 1)}`);
}

if (syncAt >= 0) {
  const spec = resolve(args[syncAt + 1]);
  emit(schemaPath, readFileSync(join(spec, "schema", "draft", "schema.json"), "utf8"));
}

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
// A root that references every definition, so that each one is emitted under its own name.
const properties: Record<string, unknown> = {};
for (const name of Object.keys(schema.$defs)) properties[name] = { $ref: `#/$defs/${name}` };
const root = {
  title: "AllDefinitions",
  description: "Every definition of the schema, by name.",
  type: "object",
  properties,
  $defs: schema.$defs,
};
let ts = await compile(root, "AllDefinitions", {
  bannerComment:
    "/* Generated by scripts/generate-types.ts from schema/schema.json. Do not edit by hand. */",
  additionalProperties: true,
  strictIndexSignatures: false,
  format: true,
  style: { singleQuote: false, printWidth: 100 },
});
ts = ts.replace(/\r\n/g, "\n");
emit(join(pkg, "src", "types", "generated.ts"), ts);
if (!ok) process.exit(1);
if (check) console.log("schema copy and generated types are up to date");
